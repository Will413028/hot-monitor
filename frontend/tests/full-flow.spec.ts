import { test, expect } from "@playwright/test";
import path from "node:path";

test("keyword, search, AI, persistence, filters, SSE, read state and scheduler", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByText("即時通知已連線", { exact: false })).toBeVisible();
  await page.getByLabel("新關鍵字").fill("Copilot");
  await page.getByRole("button", { name: "新增", exact: true }).click();
  const keyword = page.getByRole("region", { name: "監控關鍵字" });
  await expect(keyword.getByText("Copilot", { exact: true })).toBeVisible();
  await keyword.getByRole("button", { name: "暫停", exact: true }).click();
  await expect(keyword.getByText("已暫停", { exact: true })).toBeVisible();
  await keyword.getByRole("button", { name: "啟用", exact: true }).click();
  await keyword.getByRole("button", { name: "搜尋", exact: true }).click();
  const search = page.getByRole("region", { name: "多來源與全網新聞搜尋" });
  await expect(search.getByLabel("搜尋內容")).toHaveValue("Copilot");
  await search.getByRole("button", { name: "搜尋", exact: true }).click();
  await expect(search.getByText("「Copilot」共 3 筆", { exact: false })).toBeVisible();
  await search.getByRole("button", { name: "AI 分析", exact: true }).first().click();
  await expect(search.getByText("相關性 92/100", { exact: false })).toBeVisible();
  await search.getByRole("button", { name: "AI 擴展搜尋", exact: true }).click();
  await expect(search.getByText("Copilot alias", { exact: false })).toBeVisible();
  const monitor = page.getByRole("region", { name: "監控與已保存結果" });
  await monitor.getByLabel("查看保存結果的關鍵字").selectOption({ label: "Copilot" });
  await monitor.getByRole("button", { name: "立即檢查並保存" }).click();
  await expect(monitor.getByText("檢查完成，新增 3 篇。", { exact: false })).toBeVisible();
  const notifications = page.getByRole("region", { name: "通知中心" });
  await expect(notifications.getByText("最近 3 則／未讀 3 則", { exact: false })).toBeVisible();
  await notifications.getByRole("button", { name: "標為已讀" }).first().click();
  await expect(notifications.getByText("未讀 2 則", { exact: false })).toBeVisible();
  await monitor.getByRole("button", { name: "AI 分析並保存" }).first().click();
  await expect(monitor.getByText("相關性 92/100", { exact: false })).toBeVisible();
  await monitor.getByLabel("最低相關性").selectOption("80");
  await expect(monitor.getByText("第 1 頁 · 1 篇", { exact: false })).toBeVisible();
  await monitor.getByLabel("重要程度").selectOption("high");
  await monitor.getByLabel("保存結果排序").selectOption("relevance");
  await monitor.getByRole("button", { name: "啟動排程" }).click();
  await expect(monitor.getByRole("button", { name: "暫停排程" })).toBeVisible();
  await monitor.getByRole("button", { name: "暫停排程" }).click();
  await page.reload();
  await expect(notifications.getByText("未讀 2 則", { exact: false })).toBeVisible();
  await monitor.getByLabel("查看保存結果的關鍵字").selectOption({ label: "Copilot" });
  await expect(monitor.getByText("相關性 92/100", { exact: false })).toBeVisible();
  await page.screenshot({ path: path.resolve(__dirname, "../../docs/app-preview.png"), fullPage: true });
  page.once("dialog", (dialog) => dialog.accept());
  await keyword.getByRole("button", { name: "刪除", exact: true }).click();
  await expect(keyword.getByText("Copilot", { exact: true })).toHaveCount(0);
  await expect(notifications.getByText("最近 0 則／未讀 0 則", { exact: false })).toBeVisible();
  expect(errors).toEqual([]);
});
